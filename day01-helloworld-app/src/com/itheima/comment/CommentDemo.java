package com.itheima.comment;
/**
 * 3、文档注释，用于生成API文档
 * 这是一个java程序
 * 是用来讲解注释的使用。
 */
public class CommentDemo {
    /**
     * 这是一个main方法，是程序的入口
     * 必须有这个main方法，程序才能运行
     */
    public static void main(String[] args) {
        //  目标：认识三种注释的写法。
        // 1、单行注释
        // 打印1行诗句
        System.out.println("床前明月光");
        /*
            2、多行注释
            打印多行诗句
         */
        System.out.println("疑是地上霜");
        System.out.println("举头望明月");
        System.out.println("低头思故乡");
    }
}
