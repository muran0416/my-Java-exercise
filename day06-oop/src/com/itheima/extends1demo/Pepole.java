package com.itheima.extends1demo;
// 父类
// 继承的好处:1.减少代码复用 2.减少重复代码
public class Pepole {
    private char sex;
    private String name;

    public char getSex() {
        return sex;
    }

    public void setSex(char sex) {
        this.sex = sex;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
